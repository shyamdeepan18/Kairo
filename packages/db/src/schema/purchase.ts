// ─── Phase 6 — Purchase module ─────────────────────────────────────────────
//
// Document chain:  PR → PO → GRN → Invoice → Payment
//
//   purchase.requisition  internal request to buy            (no supplier, no GL)
//   purchase.po           commitment to a supplier           (no GL)
//   purchase.grn          goods received into stock          (DR inventory / CR GR-IR)   ← posts stock + GL
//   purchase.invoice      supplier bill / liability booked   (DR GR-IR / CR AP)          ← posts GL
//   purchase.payment      money paid to supplier             (DR AP / CR Bank)           ← posts GL
//
// Conventions (per ERP architecture skill):
//   • Money in PAISE. Purchase documents can exceed the 32-bit integer paise
//     ceiling (~₹2.14 Cr) used on individual accounting lines, so monetary
//     columns here use bigint (mode: 'number'). 1 INR = 100 paise. Never float.
//   • Quantities → numeric(18,4) (fractional units for process manufacturing).
//   • status is a varchar driven by StatusEngine (transitions already registered
//     for purchase.requisition / po / grn / invoice / payment).
//   • document_number generated by NumberSeriesService inside the insert tx.
//   • Every header carries the standard document columns (documentHeader()).
//   • Cross-document links (requisitionLineId, poLineId, grnLineId, etc.) give
//     full drill-down traceability and drive partial-fulfilment tracking.

// ─── Helpers ───────────────────────────────────────────────────────────────

/** A monetary column in paise. bigint avoids the integer paise overflow ceiling. */
const money = (name: string) => bigint(name, { mode: 'number' });
/** A quantity column — fractional units allowed. */
const qty = (name: string) => numeric(name, { precision: 18, scale: 4 });

/**
 * Standard transactional-document header columns.
 * Returns FRESH column builders on each call (like makeAuditColumns) so the
 * same definition can be safely spread into multiple pgTable() calls.
 */
const documentHeader = (docType: string) => ({
  id: uuid('id').default(sql`gen_random_uuid()`).primaryKey(),
  companyId: uuid('company_id').notNull().references(() => companies.id, { onDelete: 'cascade' }),
  plantId: uuid('plant_id').notNull().references(() => plants.id),

  documentType: varchar('document_type', { length: 100 }).default(docType).notNull(),
  /** Generated by NumberSeriesService — e.g. 'PO/2425/MUM/0001' */
  documentNumber: varchar('document_number', { length: 50 }).notNull(),
  /** draft | submitted | approved | rejected | closed | cancelled (StatusEngine) */
  status: varchar('status', { length: 20 }).default('draft').notNull(),

  fiscalYear: varchar('fiscal_year', { length: 5 }),
  postingDate: date('posting_date').notNull(),

  currency: varchar('currency', { length: 3 }).default('INR').notNull(),
  exchangeRate: numeric('exchange_rate', { precision: 10, scale: 6 }).default('1').notNull(),

  // ── Amounts (paise) ──────────────────────────────────────────────────────
  /** Taxable value: sum of line net amounts, net of discounts, before tax */
  netAmountPaise: money('net_amount_paise').default(0).notNull(),
  /** Header-level discount applied on top of line discounts */
  discountPaise: money('discount_paise').default(0).notNull(),
  /** Total GST (CGST + SGST + IGST + Cess) */
  taxAmountPaise: money('tax_amount_paise').default(0).notNull(),
  /** Rounding adjustment to a whole rupee */
  roundOffPaise: money('round_off_paise').default(0).notNull(),
  /** Grand total payable = net + tax + roundoff */
  totalAmountPaise: money('total_amount_paise').default(0).notNull(),

  remarks: text('remarks'),
  /** L2 custom-field values (header scope) — see Document Engine */
  custom_data: jsonb('custom_data').$type<Record<string, unknown>>().default({}).notNull(),

  // ── Workflow stamps (written by StatusEngine.prepare) ─────────────────────
  submittedBy: uuid('submitted_by').references(() => users.id),
  submittedAt: timestamp('submitted_at', { withTimezone: true }),
  approvedBy: uuid('approved_by').references(() => users.id),
  approvedAt: timestamp('approved_at', { withTimezone: true }),
  rejectedBy: uuid('rejected_by').references(() => users.id),
  rejectedAt: timestamp('rejected_at', { withTimezone: true }),
  cancelledBy: uuid('cancelled_by').references(() => users.id),
  cancelledAt: timestamp('cancelled_at', { withTimezone: true }),
  closedBy: uuid('closed_by').references(() => users.id),
  closedAt: timestamp('closed_at', { withTimezone: true }),

  createdBy: uuid('created_by').references(() => users.id),
  updatedBy: uuid('updated_by').references(() => users.id),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
});

